export const TX_CODES: TxCode[] = LIST.map(([code, name]) => ({ code, name, group: GROUP[code[0]] ?? '未知' }));

const MAP = new Map(TX_CODES.map((c) => [c.code, c]));

export function codeInfo(code: string): TxCode | undefined {
  return MAP.get(code);
}

export function codeLabel(code: string): string {
  const c = MAP.get(code);
  return c ? `${code} ${c.name}` : code || '（空）';
}

export function codeGroup(code: string): string {
  return GROUP[code?.[0] ?? ''] ?? '未知';
}

/** 中类：前两位（21 运输、22 保险、27 专业服务……） */
export function codeFamily(code: string): string {
  return code.slice(0, 2);
}
